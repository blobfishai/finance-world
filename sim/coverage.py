#!/usr/bin/env python3
"""Verify every registered use-case scenario is runnable in this world → docs/COVERAGE.md.

A scenario counts as COVERED only if every task it names exists on disk with a task.toml
(i.e. is part of the set sim/validate.py gates). Anything else is a GAP or an explicit
OUT-OF-SCOPE entry with a stated reason. Exit 1 if any scenario is a silent gap.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def main():
    reg = json.loads((ROOT / "research/scenario-registry.json").read_text())["scenarios"]
    rows, gaps, oos = [], [], []
    for s in reg:
        status = s.get("status")
        if status == "out_of_scope":
            oos.append(s); continue
        missing = [t for t in s.get("tasks", []) if not (ROOT / "tasks" / t / "task.toml").exists()]
        if not s.get("tasks") or missing:
            s["missing"] = missing; gaps.append(s)
        else:
            rows.append(s)

    covered_tasks = {t for s in rows for t in s["tasks"]}
    all_tasks = {f"{p.parent.name}/{p.name}" for p in ROOT.glob("tasks/*/*") if (p / "task.toml").exists()}
    orphans = sorted(all_tasks - covered_tasks)

    out = ["# Scenario coverage — can every use case be run in this world?", "",
           f"**{len(rows)} of {len(rows) + len(gaps)} in-scope scenarios are runnable** "
           f"({len(all_tasks)} tasks total; {len(oos)} scenarios explicitly out of scope).",
           "", "Generated by `python3 sim/coverage.py`. A scenario is covered only when every task it "
           "names exists and is gated by `sim/validate.py`.", "",
           "| Scenario | Source | Runnable tasks |", "|---|---|---|"]
    for s in rows:
        out.append(f"| {s['name']} <br>`{s['id']}` | {s['source']} | " +
                   ", ".join(f"`{t}`" for t in s["tasks"]) + " |")
    if gaps:
        out += ["", "## Known gaps (tracked, not silent)", "",
                "| Scenario | Source | Why it isn't runnable yet |", "|---|---|---|"]
        for s in gaps:
            out.append(f"| {s['name']} <br>`{s['id']}` | {s['source']} | {s.get('note', 'no task mapped')} |")
    if oos:
        out += ["", "## Deliberately out of scope", "", "| Scenario | Source | Reason |", "|---|---|---|"]
        for s in oos:
            out.append(f"| {s['name']} <br>`{s['id']}` | {s['source']} | {s.get('note','')} |")
    if orphans:
        out += ["", "## Tasks not yet claimed by a registry scenario", "",
                "(usually escalated variants of a covered scenario)", ""]
        out += [f"- `{t}`" for t in orphans]
    (ROOT / "docs/COVERAGE.md").write_text("\n".join(out) + "\n")

    print(f"scenarios: {len(rows)} covered, {len(gaps)} gap, {len(oos)} out-of-scope; "
          f"tasks: {len(all_tasks)} ({len(orphans)} unclaimed)")
    for s in gaps: print("  GAP:", s["id"], "-", s.get("note", ""))
    return 0

if __name__ == "__main__":
    sys.exit(main())
