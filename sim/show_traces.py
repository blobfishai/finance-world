#!/usr/bin/env python3
"""Run representative tasks end-to-end and write docs/TASK-TRACES.md — the receipts.

For each task: the prompt, every tool call with its real response, the verifier's per-check
verdict, and the state the run left behind. Then a summary of the model traces already on
disk. Oracle only — no benchmark runs (freeze-safe).
"""
import importlib.util, json, os, sqlite3, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sim")); sys.path.insert(0, str(ROOT / "verifiers"))
from prepare import prepare
from vcode import verify_all, verify, steps_of, parse_number, norm

SHOW = [
    ("erp_qa_fb/credit-limit-1",              "FinanceBenchmark clone — question kept verbatim, ground truth recomputed in-world"),
    ("erp_qa/collections-sparrow",            "Dunning position + payment history, policy consulted from the doc library"),
    ("collections_ops/escalate-sparrow-letter3", "WRITE task under a role grant — graded on the rows it left behind"),
    ("cross_system/tracker-formula-drift",    "Three-layer chaos: cached formula vs rows vs live ERP"),
    ("vendor_master/missing-po-inquiry",      "Interactive counterparty — the fact exists only in a reply the agent must ask for"),
    ("bank_rec/ach-return-mar",               "ACH return unwinding a settled payment"),
    ("threeway_match/tolerance-dialect-mar",  "Inverted tolerance defaults — the smaller variance blocks"),
    ("finance_qa/tsla-operating-margin-q3",   "Real XBRL facts, quarterly margin under a format constraint"),
    ("close_mgmt/two-period-close-cesq",      "Multi-step: January close, then February carrying January's late item"),
]

def load(name, tag):
    spec = importlib.util.spec_from_file_location(f"{name}_{tag}", ROOT / f"mcp/servers/{name}_server.py")
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m.S

def brief(v, n=300):
    s = json.dumps(v, default=str)
    return s if len(s) <= n else s[:n] + " …"

def check_lines(task_dir, run_dir):
    """Re-evaluate each answer check individually so the doc shows expected vs submitted."""
    cx = sqlite3.connect(Path(run_dir) / "world.sqlite")
    ans = {f: json.loads(v) for f, v in cx.execute("SELECT field, value FROM answers")}
    cx.close()
    out = []
    for d in [task_dir] + list(steps_of(task_dir)):
        p = Path(d) / "tests/checks.json"
        checks = json.loads((p if p.exists() else Path(d) / "checks.json").read_text())
        for c in checks.get("answer_checks", []):
            got = ans.get(c["field"], "<missing>")
            if c["type"] == "number":
                g, e = parse_number(got), float(c["expect"])
                tol = max(float(c.get("tol_abs", 0.01)), abs(e) * float(c.get("tol_rel", 0)))
                ok = g is not None and abs(g - e) <= tol
            elif c["type"] == "contains_all":
                ok = all(norm(x) in norm(got) for x in c["expect"])
            else:
                ok = norm(got) == norm(c["expect"])
            out.append(f"| `{c['field']}` | {brief(c['expect'], 60)} | {brief(got, 60)} | {'PASS' if ok else 'FAIL'} |")
    return out

def main():
    out = ["# Task traces — the receipts", "",
           "Generated by `python3 sim/show_traces.py`. Each task below is prepared from its own",
           "seed layers, solved by replaying its reference walk through the **real MCP tool",
           "handlers**, then graded by the deterministic verifier. Every response shown was",
           "computed from SQLite at call time. SIMULATION ONLY.", ""]
    for task, why in SHOW:
        td = ROOT / "tasks" / task
        tag = task.replace("/", "_")
        run = ROOT / ".runs/show" / tag
        env = prepare(td, run)["env"]; os.environ.update(env)
        walk = json.loads((td / "solution/walk.json").read_text())
        for sd in steps_of(td):
            if (sd / "walk.json").exists(): walk += json.loads((sd / "walk.json").read_text())

        instr = (td / "instruction.md").read_text().strip().splitlines()
        ask = " ".join(l for l in instr if l.strip() and not l.startswith(("-", "#")))[:400]

        out += [f"## `{task}`", "", f"*{why}*", "", "**Prompt (excerpt)**", "",
                "> " + ask, "", "**Tool calls and real responses**", ""]
        servers = {}
        for i, st in enumerate(walk, 1):
            s = st["server"]
            if s not in servers: servers[s] = load(s, tag)
            try: res = servers[s].call(st["tool"], st.get("args") or {})
            except Exception as e: res = {"exception": repr(e)}
            args = brief(st.get("args", {}), 170)
            out.append(f"{i}. **`{s}.{st['tool']}`** `{args}`")
            out.append(f"   → `{brief(res, 320)}`")
        v = verify_all(td, run)
        out += ["", "**Verifier**", "", "| field | expected | submitted | |", "|---|---|---|---|"]
        out += check_lines(td, run)
        out += ["", f"**reward = {v['reward']}**  ·  {v['n_tool_calls']} tool calls  ·  "
                    f"servers used: {', '.join(v['servers_used'])}" +
                    (f"  ·  failed: {v['failed']}" if v["failed"] else "  ·  all checks passed"), ""]

    # model traces already on disk
    out += ["## Model traces on disk (wave-0 scan, before the benchmark freeze)", "",
            "| model | task | trial | reward | tool calls | notes |", "|---|---|---|---|---|---|"]
    n = 0
    for p in sorted(ROOT.glob("traces/*/*/*/trial-*.json")):
        r = json.loads(p.read_text())
        if r.get("agent") == "oracle": continue
        n += 1
        note = "infra (not a model verdict)" if r.get("infra_error") else (
               "; ".join(r["failed"])[:60] if r["failed"] else "clean pass")
        out.append(f"| {r['model']} | {r['task']} | {r['trial']} | {r['reward']} | {r['n_tool_calls']} | {note} |")
    out += ["", f"{n} model trials captured. Full call paths, arguments, turn counts, cost and the",
            "agent's final message are stored per trial under `traces/<model>/<family>/<slug>/`.", ""]
    (ROOT / "docs/TASK-TRACES.md").write_text("\n".join(out) + "\n")
    print(f"wrote docs/TASK-TRACES.md — {len(SHOW)} tasks traced end-to-end, {n} model trials summarized")

if __name__ == "__main__":
    main()
